CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS accounts(
 id TEXT PRIMARY KEY,username TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL,
 owner_id TEXT REFERENCES accounts(id),totp_secret TEXT NOT NULL,mfa INTEGER NOT NULL DEFAULT 0,
 last_step BIGINT NOT NULL DEFAULT -1,created_at BIGINT NOT NULL,disabled INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS consents(
 account_id TEXT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,version TEXT NOT NULL,
 document_hash TEXT NOT NULL,name_attestation TEXT NOT NULL,accepted_at BIGINT NOT NULL,receipt TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(
 hash TEXT PRIMARY KEY,account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
 scope TEXT NOT NULL,expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS recovery_codes(
 hash TEXT PRIMARY KEY,account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS invites(
 hash TEXT PRIMARY KEY,owner_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS devices(
 id TEXT PRIMARY KEY,account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
 label TEXT NOT NULL,public_key TEXT NOT NULL UNIQUE,operation_seq BIGINT NOT NULL DEFAULT 0,created_at BIGINT NOT NULL,disabled INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS connections(
 device_id TEXT PRIMARY KEY REFERENCES devices(id) ON DELETE CASCADE,
 server_id TEXT NOT NULL,address4 TEXT NOT NULL,address6 TEXT NOT NULL,state TEXT NOT NULL,
 adblock INTEGER NOT NULL,requested_at BIGINT NOT NULL,operation_seq BIGINT NOT NULL,
 UNIQUE(server_id,address4),UNIQUE(server_id,address6));
CREATE TABLE IF NOT EXISTS rate_windows(key TEXT PRIMARY KEY,count INTEGER NOT NULL,reset_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS allocation_locks(server_id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS warnings(device_id TEXT PRIMARY KEY REFERENCES devices(id) ON DELETE CASCADE,code TEXT NOT NULL,last_announced BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS rate_expiry ON rate_windows(reset_at);
